#!/usr/bin/env python3
"""Generate schema/003_comments.sql (COMMENT ON ...) and docs/data_dictionary.md from costdb.dictionary.

Run: python3 -I pipeline/scripts/build_docs.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "pipeline"))
from costdb.dictionary import TABLES, describe  # noqa: E402
from costdb.pg import LOAD_ORDER  # noqa: E402
from costdb.schema_meta import parse_schema  # noqa: E402


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def render() -> tuple[str, str]:
    """Return (003_comments.sql text, data_dictionary.md text)."""
    meta = parse_schema()
    missing = [(t, c.name) for t, cs in meta.items() for c in cs if not describe(t, c.name)]
    if missing:
        raise SystemExit(f"undocumented columns: {missing}")
    sql = ["-- GENERATED by pipeline/scripts/build_docs.py from costdb/dictionary.py. Do not edit by hand.",
           "BEGIN;"]
    for t in LOAD_ORDER:
        sql.append(f"COMMENT ON TABLE costdb.{t} IS {q(TABLES[t][0])};")
        for c in meta[t]:
            sql.append(f"COMMENT ON COLUMN costdb.{t}.{c.name} IS {q(describe(t, c.name))};")
    sql.append("COMMIT;")

    md = ["# Data dictionary", "",
          "Generated from `pipeline/costdb/dictionary.py` and `schema/001_schema.sql` — do not edit by hand. "
          "Every column of every table is described here and as a PostgreSQL `COMMENT` (`schema/003_comments.sql`).", "",
          "## Conventions", "",
          "- **IDs**: `PREFIX-body` (`SRC-`, `PRD-`, `OBS-`, `LRT-`, `RUN-`, ...). Natural-key ids are deterministic hashes, so re-importing never duplicates. Test fixtures use `TEST-` and are rejected from production data.",
          "- **origin** (where a value came from): `observed` / `derived` / `assumed` / `missing`. **review_status** (independent check): `unreviewed` / `validated` / `flagged` / `rejected`. The two are independent.",
          "- **Dates**: price *observation* date, rate *effective period* and *retrieval* timestamp are always separate fields.",
          "- **Units**: only ids from `units`. `TON` and `GAL` exist only qualified (`TON_SHORT`, `TON_LONG`, `TON_METRIC`, `TON_REFRIG`, `GAL_US`, `GAL_IMP`). Conversion factors are exact integer ratios.",
          "- **Money**: USD, `numeric` (never float). Percentages are fractions (`0.062` = 6.2%) except `per_100_payroll` rates.",
          "- **CSV interchange** (`data/csv/*.csv`): header row, empty field = NULL, booleans `true/false`, arrays as PostgreSQL literals `{a,b}`, jsonb as JSON text. Generated columns are not in the CSV.",
          "- **Append-only** tables (triggers forbid UPDATE of data fields and any DELETE): `price_observations`, `labor_rates`, `equipment_rates`, `productivity_observations`, `burden_rates`, `index_values`, `product_consumption`, `bid_benchmarks`. Only `review_status`, `reviewed_by`, `reviewed_at`, `notes` may change.", "",
          "## Tables", ""]
    for t in LOAD_ORDER:
        desc, _ = TABLES[t]
        md += [f"### `{t}`", "", desc, "", "| column | type | description |", "|---|---|---|"]
        for c in meta[t]:
            typ = c.sql_type + (" (generated)" if c.generated else "") + (f" → `{c.references[0]}.{c.references[1]}`" if c.references else "")
            md.append(f"| `{c.name}` | {typ} | {describe(t, c.name).replace('|', '/')} |")
        md.append("")
    return "\n".join(sql) + "\n", "\n".join(md)


def main() -> int:
    sql, md = render()
    (ROOT / "schema" / "003_comments.sql").write_text(sql, encoding="utf-8")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "data_dictionary.md").write_text(md, encoding="utf-8")
    print(f"wrote schema/003_comments.sql ({sql.count(chr(10))} lines) and docs/data_dictionary.md ({md.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
